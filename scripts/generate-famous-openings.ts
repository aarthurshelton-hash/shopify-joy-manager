import { writeFileSync } from 'node:fs';
import { famousGames, carlsenLegendaryGames } from '../src/lib/chess/famousGames';
import { detectOpeningFromPgn } from '../src/lib/chess/openingDetector';
import { choosePaletteForGame } from '../src/lib/chess/gamePalette';

const out: Record<string, { eco: string; name: string; fullName: string }> = {};
const palettes: Record<string, string> = {};
for (const g of [...famousGames, ...carlsenLegendaryGames]) {
  const o = detectOpeningFromPgn(g.pgn);
  if (o) out[g.id] = { eco: o.eco, name: o.name, fullName: o.fullName };
  palettes[g.id] = choosePaletteForGame(g.pgn);
}

const body = Object.entries(out)
  .map(([id, o]) => `  ${JSON.stringify(id)}: ${JSON.stringify(o)},`)
  .join('\n');

writeFileSync(
  new URL('../src/lib/chess/famousGameOpenings.ts', import.meta.url),
  `// Generated by scripts/generate-famous-openings.ts (npx tsx scripts/generate-famous-openings.ts).
// Saved opening and chosen palette per famous game so the UI does not replay every PGN on load.
import type { PaletteId } from './pieceColors';

export interface SavedOpening {
  eco: string;
  name: string;
  fullName: string;
}

export const FAMOUS_GAME_OPENINGS: Record<string, SavedOpening> = {
${body}
};

export const FAMOUS_GAME_PALETTES: Record<string, PaletteId> = {
${Object.entries(palettes).map(([id, p]) => `  ${JSON.stringify(id)}: ${JSON.stringify(p)},`).join('\n')}
};
`,
);
console.log(`saved ${Object.keys(out).length} openings`);
