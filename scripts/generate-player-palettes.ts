import { writeFileSync } from 'node:fs';
import { famousGames, carlsenLegendaryGames } from '../src/lib/chess/famousGames';
import { fischerTop100 } from '../src/lib/book/fischerGames';
import { carlsenTop100 } from '../src/lib/book/carlsenGames';
import { pgnMoves } from '../src/lib/chess/gamePalette';
import { buildPlayerProfiles, matchPaletteForGame, type SidePalette, type StyleGame } from '../src/lib/chess/playerStyle';

// Every game in every collection, keyed the way the UI looks it up.
const sources: [string, StyleGame][] = [
  ...[...famousGames, ...carlsenLegendaryGames].map((g) => [g.id, g] as [string, StyleGame]),
  ...fischerTop100.map((g) => [`fischer:${g.id}`, g] as [string, StyleGame]),
  ...carlsenTop100.map((g) => [`carlsen:${g.id}`, g] as [string, StyleGame]),
];

// The same game can appear in several collections; count it once.
const canonical = new Map<string, StyleGame>();
const games: StyleGame[] = [];
for (const [, g] of sources) {
  const k = pgnMoves(g.pgn).join(' ');
  if (!canonical.has(k)) {
    canonical.set(k, g);
    games.push(g);
  }
}
const profiles = buildPlayerProfiles(games);

const r2 = (x: number) => Math.round(x * 100) / 100;
const pack = (s: SidePalette) => [s.paletteId, s.key, s.games, r2(s.style.energy), r2(s.style.texture), r2(s.style.length), s.yielded ? 1 : 0];
const match: Record<string, unknown[]> = {};
for (const [key, g] of sources) {
  const c = canonical.get(pgnMoves(g.pgn).join(' '))!;
  const m = matchPaletteForGame({ ...g, id: c.id }, profiles);
  if (m) match[key] = [...pack(m.white), ...pack(m.black)];
}

const players: Record<string, { name: string; games: number; paletteId: string; journey: [number, string][] }> = {};
for (const p of [...profiles.values()].sort((a, b) => b.history.length - a.history.length)) {
  const journey: [number, string][] = [];
  for (const h of p.history) if (journey[journey.length - 1]?.[1] !== h.paletteId) journey.push([h.year, h.paletteId]);
  const last = p.history[p.history.length - 1];
  players[p.key] = { name: p.name, games: last.games, paletteId: last.paletteId, journey };
}

writeFileSync(
  new URL('../src/lib/chess/playerPalettes.ts', import.meta.url),
  `// Generated by scripts/generate-player-palettes.ts (npx tsx scripts/generate-player-palettes.ts).
// Player colour identities and per-game match palettes; see src/lib/chess/playerStyle.ts for the logic.
import type { PaletteId } from './pieceColors';

/** [palette, playerKey, games, energy, texture, length, yielded] for White, then the same for Black. */
export type SavedMatchPalette = [PaletteId, string, number, number, number, number, 0 | 1, PaletteId, string, number, number, number, number, 0 | 1];

export interface SavedPlayerPalette {
  name: string;
  games: number;
  paletteId: PaletteId;
  /** [year, palette] each time the player's palette changed. */
  journey: [number, PaletteId][];
}

export const MATCH_PALETTES: Record<string, SavedMatchPalette> = {
${Object.entries(match).map(([k, v]) => `  ${JSON.stringify(k)}: ${JSON.stringify(v)},`).join('\n')}
};

export const PLAYER_PALETTES: Record<string, SavedPlayerPalette> = ${JSON.stringify(players)};
`,
);
console.log(`players ${Object.keys(players).length}, match palettes ${Object.keys(match).length}/${sources.length}`);
